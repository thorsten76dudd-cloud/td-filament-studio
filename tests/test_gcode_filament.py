    def test_parse_header_comment(self) -> None:
        with tempfile.NamedTemporaryFile("w", suffix=".gcode", delete=False, encoding="utf-8") as f:
            f.write("; generated\n; total filament used [g] = 47.3\nG28\n")
            path = Path(f.name)
        try:
            self.assertAlmostEqual(parse_filament_grams_from_file(path), 47.3, places=1)
        finally:
            path.unlink(missing_ok=True)

    def test_estimate_from_printer_metadata(self) -> None:
        state = {
            "retGcodeFileInfo2": [
                {
                    "name": "part.gcode",
                    "filamentWeight": "38.5",
                    "material": "PETG",
                    "materialColors": "#000000",
                }
            ]
        }
        est = estimate_grams_for_slot(state, "part.gcode", 0)
        self.assertIsNotNone(est)
        assert est is not None
        self.assertEqual(est[0], 38)

    def test_parse_filament_weight_list(self) -> None:
        specs = parse_filament_specs(
            {"filamentWeight": "12.5,0", "materialColors": "#fff;#000", "material": "PLA;PLA"}
        )
        self.assertEqual(len(specs), 4)
        self.assertAlmostEqual(specs[0].weight_g or 0, 12.5, places=1)


    def test_parse_print_temps_from_metadata(self) -> None:
        n, b = parse_gcode_print_temps(
            {"nozzleTemp": 25500, "bedTemp": 7000, "bed_temp_from_file": 70.0}
        )
        self.assertEqual(n, 255)
        self.assertEqual(b, 70)

    def test_build_preheat_steps(self) -> None:
        steps = build_preheat_params({"nozzleTemp": 24000, "bedTemp": 6000})
        self.assertEqual(steps[0], {"nozzleTempControl": 240})
        self.assertEqual(steps[1], {"bedTempControl": {"num": 0, "val": 60}})

    def test_parse_color_from_gcode_header(self) -> None:
        with tempfile.NamedTemporaryFile("w", suffix=".gcode", delete=False, encoding="utf-8") as f:
            f.write("; generated by Creality Print\n; default_filament_colour = #1E90FF\n; material = PETG\nG28\n")
            path = Path(f.name)
        try:
            colors, materials = parse_filament_colors_from_gcode_file(path)
            self.assertEqual(colors, ["#1E90FF"])
            self.assertTrue(any("PETG" in m for m in materials))
        finally:
            path.unlink(missing_ok=True)

